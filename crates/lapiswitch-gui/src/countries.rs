    fn choices_match_the_patcher_and_have_flags() {
        assert_eq!(
            COUNTRIES.len(),
            lapiswitch_core::country::CHOICE_CODES.len()
        );
        for code in lapiswitch_core::country::CHOICE_CODES {
            assert!(find(code).is_some());
            let _ = flag(code);
        }
    }
